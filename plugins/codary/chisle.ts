// Выключить насовсем: команда /chisle off (флаг лежит в папке данных); включить: /chisle on. В отдельном чате можно написать «stop chisle» или «обычный режим».
import path from "node:path"
import fs from "node:fs/promises"
import { Global } from "@opencode-ai/core/global"

const flagFile = () => path.join(Global.Path.data, "codary", "chisle-off")

export async function chisleEnabled() {
  if (process.env.CODARY_CHISLE === "0") return false
  try {
    await fs.access(flagFile())
    return false
  } catch {
    return true
  }
}

export async function setChisle(on: boolean) {
  if (on) await fs.rm(flagFile(), { force: true })
  else {
    await fs.mkdir(path.dirname(flagFile()), { recursive: true })
    await fs.writeFile(flagFile(), "off\n")
  }
}

